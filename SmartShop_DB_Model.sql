SELECT
    c.TABLE_NAME,
    c.CONSTRAINT_NAME,
    c.CONSTRAINT_TYPE,
    cc.COLUMN_NAME,
    c.R_CONSTRAINT_NAME
FROM USER_CONSTRAINTS c
JOIN USER_CONS_COLUMNS cc
    ON c.CONSTRAINT_NAME = cc.CONSTRAINT_NAME
   AND c.TABLE_NAME = cc.TABLE_NAME
WHERE c.TABLE_NAME IN (
    'SUPPLIERS',
    'CUSTOMERS',
    'PRODUCTS',
    'PURCHASES',
    'PURCHASE_ITEMS',
    'POS_SHIFTS',
    'SALES',
    'SALE_ITEMS',
    'PAYMENTS',
    'HELD_CARTS'
)
AND c.CONSTRAINT_TYPE IN ('P', 'R')
ORDER BY c.TABLE_NAME, c.CONSTRAINT_TYPE, cc.POSITION;

SELECT
    fk.TABLE_NAME AS CHILD_TABLE,
    fkc.COLUMN_NAME AS FK_COLUMN,
    pk.TABLE_NAME AS PARENT_TABLE,
    pkc.COLUMN_NAME AS PARENT_COLUMN,
    fk.CONSTRAINT_NAME AS FK_NAME
FROM USER_CONSTRAINTS fk
JOIN USER_CONS_COLUMNS fkc
    ON fk.CONSTRAINT_NAME = fkc.CONSTRAINT_NAME
JOIN USER_CONSTRAINTS pk
    ON fk.R_CONSTRAINT_NAME = pk.CONSTRAINT_NAME
JOIN USER_CONS_COLUMNS pkc
    ON pk.CONSTRAINT_NAME = pkc.CONSTRAINT_NAME
WHERE fk.CONSTRAINT_TYPE = 'R'
AND fk.TABLE_NAME IN (
    'SUPPLIERS',
    'CUSTOMERS',
    'PRODUCTS',
    'PURCHASES',
    'PURCHASE_ITEMS',
    'POS_SHIFTS',
    'SALES',
    'SALE_ITEMS',
    'PAYMENTS',
    'HELD_CARTS'
)
ORDER BY fk.TABLE_NAME;

