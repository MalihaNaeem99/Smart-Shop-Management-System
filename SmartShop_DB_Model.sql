CREATE TABLE SUPPLIERS (
    SUPPLIER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SUPPLIER_CODE VARCHAR2(30) UNIQUE,
    SUPPLIER_NAME VARCHAR2(100) NOT NULL,
    CATEGORY VARCHAR2(50),
    CONTACT_PERSON VARCHAR2(100),
    PHONE VARCHAR2(20),
    EMAIL VARCHAR2(100),
    NTN VARCHAR2(30),
    PAYMENT_TERMS VARCHAR2(50),
    LEAD_TIME_DAYS NUMBER(5),
    CITY VARCHAR2(50),
    BALANCE_PAYABLE NUMBER(12,2) DEFAULT 0,
    STATUS VARCHAR2(20) DEFAULT 'Active'
);

CREATE TABLE CUSTOMERS (
    CUSTOMER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(20) UNIQUE NOT NULL,
    EMAIL VARCHAR2(100),
    TIER VARCHAR2(20) DEFAULT 'Silver',
    POINTS NUMBER(10) DEFAULT 50,
    TOTAL_SPENT NUMBER(12,2) DEFAULT 0,
    VISITS_COUNT NUMBER(10) DEFAULT 0,
    JOINED_DATE DATE DEFAULT SYSDATE
);

CREATE TABLE PRODUCTS (
    PRODUCT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SKU VARCHAR2(30) UNIQUE,
    BARCODE VARCHAR2(50) UNIQUE,
    PRODUCT_NAME VARCHAR2(100) NOT NULL,
    CATEGORY VARCHAR2(50),
    DEPARTMENT VARCHAR2(50),
    AISLE VARCHAR2(50),
    COST_PRICE NUMBER(12,2) DEFAULT 0,
    SELLING_PRICE NUMBER(12,2) NOT NULL,
    STOCK_QUANTITY NUMBER(12,3) DEFAULT 0,
    UNIT VARCHAR2(30),
    BATCH_NO VARCHAR2(50),
    EXPIRY_DATE DATE,
    SUPPLIER_ID NUMBER,
    MIN_THRESHOLD NUMBER(10) DEFAULT 5,
    IS_WEIGHABLE CHAR(1) DEFAULT 'N',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP,

    CONSTRAINT FK_PRODUCT_SUPPLIER
    FOREIGN KEY (SUPPLIER_ID)
    REFERENCES SUPPLIERS(SUPPLIER_ID),

    CONSTRAINT CHK_PRODUCT_PRICE
    CHECK (SELLING_PRICE >= 0),

    CONSTRAINT CHK_PRODUCT_STOCK
    CHECK (STOCK_QUANTITY >= 0),

    CONSTRAINT CHK_WEIGHABLE
    CHECK (IS_WEIGHABLE IN ('Y','N'))
);

CREATE TABLE PURCHASES (
    PURCHASE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PO_NUMBER VARCHAR2(40),
    GRN_NUMBER VARCHAR2(40) UNIQUE NOT NULL,
    SUPPLIER_ID NUMBER NOT NULL,
    INVOICE_REF VARCHAR2(50),
    PURCHASE_DATE DATE DEFAULT SYSDATE,
    PAYMENT_TERMS VARCHAR2(50),
    RECEIVED_BY VARCHAR2(100),
    SUBTOTAL NUMBER(12,2) DEFAULT 0,
    TAX_AMOUNT NUMBER(12,2) DEFAULT 0,
    GRAND_TOTAL NUMBER(12,2) DEFAULT 0,
    STATUS VARCHAR2(50),
    RECEIVED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_PURCHASE_SUPPLIER
    FOREIGN KEY (SUPPLIER_ID)
    REFERENCES SUPPLIERS(SUPPLIER_ID)
);

CREATE TABLE PURCHASE_ITEMS (
    PURCHASE_ITEM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PURCHASE_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    QUANTITY NUMBER(12,3) NOT NULL,
    COST_PRICE NUMBER(12,2) NOT NULL,
    BATCH_NO VARCHAR2(50),
    EXPIRY_DATE DATE,
    TOTAL_COST NUMBER(12,2),

    CONSTRAINT FK_PI_PURCHASE
    FOREIGN KEY (PURCHASE_ID)
    REFERENCES PURCHASES(PURCHASE_ID),

    CONSTRAINT FK_PI_PRODUCT
    FOREIGN KEY (PRODUCT_ID)
    REFERENCES PRODUCTS(PRODUCT_ID)
);

CREATE TABLE POS_SHIFTS (
    SHIFT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COUNTER_NO VARCHAR2(30),
    CASHIER_NAME VARCHAR2(100),
    OPENED_AT TIMESTAMP,
    CLOSING_TIME TIMESTAMP,
    OPENING_FLOAT NUMBER(12,2) DEFAULT 0,
    CASH_DROPS NUMBER(12,2) DEFAULT 0,
    EXPECTED_CASH NUMBER(12,2),
    ACTUAL_CASH NUMBER(12,2),
    STATUS VARCHAR2(20) DEFAULT 'Open'
);

CREATE TABLE SALES (
    SALE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INVOICE_NUMBER VARCHAR2(40) UNIQUE NOT NULL,
    SHIFT_ID NUMBER,
    CUSTOMER_ID NUMBER,
    SALE_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    SUBTOTAL NUMBER(12,2),
    COST_SUBTOTAL NUMBER(12,2),
    GROSS_PROFIT NUMBER(12,2),
    DISCOUNT NUMBER(12,2) DEFAULT 0,
    COUPON_CODE VARCHAR2(30),
    TAX_RATE NUMBER(5,2),
    TAX_AMOUNT NUMBER(12,2),
    GRAND_TOTAL NUMBER(12,2),
    AMOUNT_TENDERED NUMBER(12,2),
    CHANGE_DUE NUMBER(12,2),
    PAYMENT_METHOD VARCHAR2(30),
    POINTS_EARNED NUMBER(10) DEFAULT 0,
    POINTS_REDEEMED NUMBER(10) DEFAULT 0,
    CASHIER VARCHAR2(100),
    STATUS VARCHAR2(20) DEFAULT 'Completed',
    VOID_REASON VARCHAR2(200),
    VOIDED_AT TIMESTAMP,

    CONSTRAINT FK_SALE_SHIFT
    FOREIGN KEY (SHIFT_ID)
    REFERENCES POS_SHIFTS(SHIFT_ID),

    CONSTRAINT FK_SALE_CUSTOMER
    FOREIGN KEY (CUSTOMER_ID)
    REFERENCES CUSTOMERS(CUSTOMER_ID)
);

CREATE TABLE SALE_ITEMS (
    SALE_ITEM_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SALE_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    PRODUCT_NAME VARCHAR2(100),
    QUANTITY NUMBER(12,3) NOT NULL,
    UNIT VARCHAR2(30),
    UNIT_PRICE NUMBER(12,2) NOT NULL,
    COST_PRICE NUMBER(12,2),
    LINE_TOTAL NUMBER(12,2),

    CONSTRAINT FK_SI_SALE
    FOREIGN KEY (SALE_ID)
    REFERENCES SALES(SALE_ID),

    CONSTRAINT FK_SI_PRODUCT
    FOREIGN KEY (PRODUCT_ID)
    REFERENCES PRODUCTS(PRODUCT_ID)
);

CREATE TABLE PAYMENTS (
    PAYMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SALE_ID NUMBER NOT NULL,
    PAYMENT_METHOD VARCHAR2(30) NOT NULL,
    AMOUNT NUMBER(12,2) NOT NULL,
    PAYMENT_REFERENCE VARCHAR2(100),
    PAYMENT_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_PAYMENT_SALE
    FOREIGN KEY (SALE_ID)
    REFERENCES SALES(SALE_ID)
);

CREATE TABLE HELD_CARTS (
    HELD_CART_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TICKET_NUMBER VARCHAR2(40) UNIQUE,
    CUSTOMER_ID NUMBER,
    CUSTOMER_NAME VARCHAR2(100),
    CUSTOMER_PHONE VARCHAR2(20),
    CART_ITEMS_JSON CLOB,
    SUBTOTAL NUMBER(12,2),
    ITEM_COUNT NUMBER(10),
    PARKED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    STATUS VARCHAR2(20) DEFAULT 'Held',

    CONSTRAINT FK_HELD_CUSTOMER
    FOREIGN KEY (CUSTOMER_ID)
    REFERENCES CUSTOMERS(CUSTOMER_ID)
);

